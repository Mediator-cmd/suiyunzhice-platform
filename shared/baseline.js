/**
 * 申报书实测基准场景 —— 让平台能复现申报材料里引用的每一个数字。
 *
 * 为什么需要它：
 *   平台的实时演示跑的是内置模拟器，识别结果随时间波动，
 *   靶向网格数、药耗、耗时都会跟着变（同一时刻可能是 19 格 / 0.57 L，
 *   下一刻变成 24 格 / 0.72 L）。这样一来，申报书里写的数字
 *   就无法在现场演示时被复现 —— 评委看到的和材料里写的不一样。
 *
 *   所以这里把「申报书实测基准场景」固化成一份确定性数据：
 *     全田覆盖：航程 3110 m / 耗时 6.56 min / 药耗 25.2 L / 耗电 29.2%
 *     靶向点喷：19 个病灶格 / 耗时 3.61 min / 药耗 0.57 L
 *               覆盖率 Cr = 1.00 / 溢出 0 亩 / 节约 97.7%
 *     相对人工手画：耗时 −64.5% / 航程 −35.0% / 转弯 −78.4% / 重喷 12.0%→0
 *
 *   这套场景的每一个数字都由 shared/planner.js 的同一套算法算出，
 *   不是写死的常量 —— 改了规划算法，这里会跟着变，避免"两套数字"。
 *
 * 基准靶向网格：R12—R14 × C25—C28 的密集病灶区，再加 3 个离散格，
 * 共 19 格；簇内 5 m 网格按 1 m 窄幅并排 5 条喷洒带 → 单格喷洒长 25 m，
 * 19 格合计 475 m，× 12 L/ha 恰好 0.57 L。
 */

/** 申报书实测基准：靶向点喷的 19 个病灶格（行, 列），均以 0 为基 */
export const BASELINE_TARGET_CELLS = (() => {
  const cells = [];
  for (let r = 11; r < 15; r++) {
    for (let c = 24; c < 28; c++) cells.push({ row: r, col: c });
  }
  cells.push({ row: 15, col: 24 });
  cells.push({ row: 10, col: 25 });
  cells.push({ row: 15, col: 25 });
  return cells;
})();

/** 基准场景的作业参数（与平台默认作业参数一致） */
export const BASELINE_PARAMS = {
  headingDeg: 0,
  speedMs: 8,
  swathM: 1.0,        // 靶向点喷用 1 m 窄幅喷施机构
  fullSwathM: 7,      // 全田覆盖用整机喷幅
  targetDoseLha: 12,
  turnRadiusM: 2.5,
};

/** 场景口径标记：出现在作业单与接口返回里，便于前端标注「实测基准」 */
export const BASELINE_SCENARIO_ID = 'baseline-2026';
